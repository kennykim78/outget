#!/usr/bin/env node
// docs/design/tokens.json -> client/src/styles/tokens.css (의존성 0, Node 20)
// 사용: node scripts/gen-tokens.mjs [--check]
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = resolve(root, 'docs/design/tokens.json');
const OUT = resolve(root, 'client/src/styles/tokens.css');

const t = JSON.parse(readFileSync(SRC, 'utf8'));
let leaves = 0;
let vars = 0;
const lines = [];
const decl = (name, value, isLeaf = true) => {
  lines.push(`  --ws-${name}: ${value};`);
  vars++;
  if (isLeaf) leaves++;
};

lines.push(`/* GENERATED by scripts/gen-tokens.mjs from docs/design/tokens.json v${t.version} — 직접 수정 금지 */`);
lines.push(':root {');
lines.push('  color-scheme: light;');

lines.push('', '  /* 색 */');
for (const c of t.color.tokens) decl(c.name, c.value);

lines.push('', '  /* 타입: 패밀리 */');
for (const [k, v] of Object.entries(t.type.families)) decl(`font-${k}`, v);

lines.push('', '  /* 타입: 스타일 (size / lh / weight / tracking) */');
const styles = t.type.groups.flatMap((g) => g.styles.map((s) => ({ ...s, family: g.family })));
for (const s of styles) {
  decl(`type-${s.name}-size`, s.fontSize);
  decl(`type-${s.name}-lh`, s.lineHeight);
  decl(`type-${s.name}-weight`, String(s.fontWeight));
  if (s.letterSpacing) decl(`type-${s.name}-tracking`, s.letterSpacing);
  else decl(`type-${s.name}-tracking`, 'normal', false); // 기본값(토큰 리프 아님)
}

lines.push('', '  /* 간격 */');
for (const x of t.spacing.tokens) decl(x.name, x.value);
lines.push('', '  /* 라운드 */');
for (const x of t.radius.tokens) decl(x.name, x.value);
lines.push('', '  /* 그림자 (모바일 바텀시트·스티키 액션바만) */');
for (const x of t.shadow.tokens) decl(x.name, x.value);

lines.push('', '  /* 레이아웃');
lines.push('     @media 브레이크포인트는 변수 사용 불가 — 리터럴로 쓴다: ≥768px (bp-tablet), ≥1024px (bp-desktop).');
lines.push('     아래 bp-* 변수는 참조용. */');
for (const x of t.layout.tokens) decl(x.name, x.value);

// 파생 (스펙 22 §1.5, 고정 목록 — tokens.json 리프 아님)
const derived = [
  ['scrim', 'rgba(47, 43, 39, 0.42)'],
  ['modal-w-tablet', '600px'],
  ['content-tablet', '960px'],
  ['touch', '44px'],
  ['focus-ring', '2px solid var(--ws-focus)'],
  ['focus-ring-offset', '2px'],
  ['disabled-opacity', '0.4'],
  ['pressed-brightness', 'brightness(0.92)'],
  ['motion', '120ms'],
  ['bundle-w', '220px'],
  ['bundle-w-wide', '352px'],
  ['vet-w', '240px'],
  ['vet-w-wide', '262px'],
  ['review-w', '280px'],
  ['review-w-wide', '320px'],
  ['product-card-w-wide', '176px'],
  ['avatar-lg-disc', '120px'],
  ['avatar-lg-img', '96px'],
  ['avatar-md-disc', '52px'],
  ['avatar-md-img', '40px'],
  ['avatar-sm-disc', '32px'],
  ['avatar-sm-img', '24px'],
  ['avatar-type-disc', '72px'],
  ['avatar-type-img', '56px'],
];
lines.push('', '  /* 파생 (스펙 §1.5 고정 목록 — tokens.json 리프 아님). *-wide = ≥1024px 값, avatar *-disc/-img = 바깥 원 / 안쪽 이미지 */');
for (const [n, v] of derived) decl(n, v, false);
lines.push('}', '');

lines.push('/* 타입 유틸리티 */');
for (const s of styles) {
  const n = s.name;
  lines.push(`.ws-t-${n} {`);
  lines.push(`  font-family: var(--ws-font-${s.family});`);
  lines.push(`  font-size: var(--ws-type-${n}-size);`);
  lines.push(`  line-height: var(--ws-type-${n}-lh);`);
  lines.push(`  font-weight: var(--ws-type-${n}-weight);`);
  lines.push(`  letter-spacing: var(--ws-type-${n}-tracking);`);
  if (n.startsWith('spec')) lines.push('  font-variant-numeric: tabular-nums;');
  lines.push('}');
}

const css = lines.join('\n') + '\n';
const norm = (s) => s.replace(/\r\n/g, '\n');

if (process.argv.includes('--check')) {
  const disk = existsSync(OUT) ? norm(readFileSync(OUT, 'utf8')) : null;
  if (disk !== css) {
    console.error('tokens.css가 tokens.json과 다릅니다. node scripts/gen-tokens.mjs 로 재생성하세요.');
    process.exit(1);
  }
  console.log(`tokens: ${leaves} leaves → ${vars} vars (check OK)`);
} else {
  writeFileSync(OUT, css);
  console.log(`tokens: ${leaves} leaves → ${vars} vars`);
}
